/// 삼아 226장을 훑고, 색 차이 합(SAD)이 가장 작은 자리를 적어 둔 표다. 맞는 자리와 아닌
/// 자리의 점수가 뚜렷하게 갈린다. 없는 자리는 -1 이다.
///
/// <list type="bullet">
///   <item>항구 — 리스본(0번) 그림의 탑 14x36. 2만점대가 맞는 자리고 6만점대는 탑이 아예
///         없는 그림이라 4만점으로 갈랐다. 70곳.</item>
///   <item>조선소 — 그림이 두 벌이다(리스본의 큰 것, 128번의 작은 것). 둘 다 대 보고 잘 맞는
///         쪽을 썼고 크기는 둘 다 28x20 이다. 5만점으로 갈라 70곳. 5만점을 넘긴 것 중에는
///         <b>지붕만 다른 같은 모양 건물</b>(191번의 노란 지붕)이 걸려 있어 더 늘리지 않았다.</item>
///   <item>술집 — 리스본 그림의 붉은 지붕 집 28x20. 어느 것이 술집인지는 게임 화면을 찍은
///         조각으로 짚었다(1.75배로 줄여 대니 리스본 (114,150)에 딱 맞았다).
