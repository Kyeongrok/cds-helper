/// <summary>
/// 도시 그림(<see cref="CityPictures"/>) 안에서 건물이 서 있는 자리. 그림을 눌러 항구·조선소로
/// 들어갈 수 있게 하려고 둔다.
/// </summary>
/// <remarks>
/// 게임은 도시 화면에서 건물마다 이름표를 띄우지만 그 자리표는 아직 EXE 에서 못 찾았다.
/// 대신 <b>건물 그림이 도시마다 똑같다</b>는 것을 이용했다 — 한 도시의 건물 그림을 본으로
/// 삼아 226장을 훑고, 색 차이 합(SAD)이 가장 작은 자리를 적어 둔 표다. 맞는 자리와 아닌
/// 자리의 점수가 뚜렷하게 갈린다. 없는 자리는 -1 이다.
///
/// <list type="bullet">
///   <item>항구 — 리스본(0번) 그림의 탑 14x36. 2만점대가 맞는 자리고 6만점대는 탑이 아예
///         없는 그림이라 4만점으로 갈랐다. 70곳.</item>
///   <item>조선소 — 그림이 두 벌이다(리스본의 큰 것, 128번의 작은 것). 둘 다 대 보고 잘 맞는
///         쪽을 썼고 크기는 둘 다 28x20 이다. 5만점으로 갈라 70곳. 5만점을 넘긴 것 중에는
///         <b>지붕만 다른 같은 모양 건물</b>(191번의 노란 지붕)이 걸려 있어 더 늘리지 않았다.</item>
///   <item>술집 — 리스본 그림의 붉은 지붕 집 28x20. 어느 것이 술집인지는 게임 화면을 찍은
///         조각으로 짚었다(1.75배로 줄여 대니 리스본 (114,150)에 딱 맞았다).
///         3만점대까지가 맞는 자리고 그 위는 6만점부터라 4만점으로 갈랐다. 85곳.</item>
///   <item>시장 60x30 · 교역소 43x20 · 교회 28x52 · 조합 26x33 · 여관 26x15 — 이 다섯은
///         게임 화면 조각을 <b>상관계수(NCC)</b> 로 맞춰 리스본에서 자리를 짚었다(다섯 다
///         1.75배에서 맞았고 NCC 0.86~0.95). 평균 오차로 재면 하늘·풀밭 같은 밋밋한 자리가
///         이겨서 엉뚱한 데를 짚는다 — 그래서 NCC 로 바꿨다.
///         자리 찾기는 지중해·이베리아 59곳에서만 돌렸다(경도 -12~37, 위도 28~47).
///         잡힌 곳은 시장 29 · 교역소 27 · 교회 25 · 조합 8 · 여관 42곳이고, 점수가
///         2~6만점대와 13만점대로 뚜렷하게 갈려 그 사이를 잣대로 삼았다.</item>
/// </list>
/// 한 도시에 시설이 다 잡히지는 않는다 — 못 찾은 쪽은 그림이 다른 벌이거나 그 도시에 없다.
/// 유럽식이 아닌 그림(이슬람·아시아)은 건물을 아주 다르게 그려서 거의 안 잡힌다.
/// 붙여 본 그림으로 다 확인했다.
/// </remarks>
